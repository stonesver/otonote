export function translateTeamPlanningText(value) {
  if(value==null)return value;
  const text=String(value);
  if(text.trim()!==text&&text.trim())return `${text.match(/^\s*/)?.[0]??''}${translateTeamPlanningText(text.trim())}${text.match(/\s*$/)?.[0]??''}`;
  if(teamPlanningEnglish[text])return teamPlanningEnglish[text];
  for(const [pattern,replacement] of patterns)if(pattern.test(text))return text.replace(pattern,replacement);
  if(text.endsWith(' 已调整发挥条件，请展开上方设置查看。'))return `${translateTeamPlanningText(text.replace(' 已调整发挥条件，请展开上方设置查看。',''))} Performance settings have been adjusted; expand the controls above to review them.`;
  if(text.endsWith(' · 缺失养成按满养成参考'))return `${translateTeamPlanningText(text.replace(' · 缺失养成按满养成参考',''))} · missing levels use maximum-upgrade references`;
  return text;
}
export function planningUiText(value,locale) {return locale==='en'?translateTeamPlanningText(value):value;}

/** Explicit one-shot translation for dynamic tool output; no observer or input-value writes. */
export function translatePlanningSubtree(root, locale) {
  if(locale!=='en'||!root)return 0;
  const skip='[data-ui-entity],[translate="no"],script,style,code,pre,textarea,[contenteditable="true"]';
  if(root.parentElement?.closest?.(skip))return 0;
  let changed=0;
  function walk(node) {
    if(node.nodeType===1&&node.matches?.(skip))return;
    if(node.nodeType===3){
      const value=node.nodeValue??'',text=value.replace(/\s+/g,' ').trim();
      if(!text)return;
      const translated=translateTeamPlanningText(text);
      if(translated!==text){node.nodeValue=`${value.match(/^\s*/)?.[0]??''}${translated}${value.match(/\s*$/)?.[0]??''}`;changed++;}
      return;
    }
    for(const child of node.childNodes??[])walk(child);
  }
  walk(root);return changed;
}
